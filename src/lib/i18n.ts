const DICTS: Record<Language, Dict> = { en, hi, kn, ta, te };

export type PhraseKey = keyof typeof en & string;

/** Translate a key, interpolating `{0}`, `{1}` … Falls back to English. */
export function t(key: PhraseKey | string, lang: Language, params: string[] = []): string {
  const template = DICTS[lang]?.[key] ?? en[key] ?? String(key);
  return params.reduce<string>(
    (acc, value, index) => acc.split(`{${index}}`).join(value),
    template,
  );
}

/** How complete a language's UI dictionary is — surfaced in the language menu. */
export function coverage(lang: Language): number {
  if (lang === "en") return 100;
  const keys = Object.keys(en);
  const have = keys.filter((k) => Boolean(DICTS[lang][k])).length;
  return Math.round((have / keys.length) * 100);
}
